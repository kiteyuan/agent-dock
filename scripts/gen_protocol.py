#!/usr/bin/env python3
"""Generate Device Protocol bindings from protocol/device.schema.json.

    python scripts/gen_protocol.py          # write generated files
    python scripts/gen_protocol.py --check  # exit 1 if any file is stale (CI / pre-commit)

Outputs (never edit by hand):
    runtime/protocol/_generated.py               enums + payload TypedDicts
    clients/shared/protocol_gen.py               dependency-free constants for Python devices
    desktop/web/js/protocol.gen.js               MSG / AGENT constants + JSDoc payload typedefs
    clients/mobile/lib/protocol/protocol.gen.dart Msg / AgentEvt constants
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "protocol" / "device.schema.json"
HEADER = "Generated by scripts/gen_protocol.py from protocol/device.schema.json — DO NOT EDIT."


@dataclass(frozen=True)
class Message:
    def_name: str
    wire: str
    const: str
    direction: str
    status: str
    family: str
    description: str
    schema: dict[str, Any]


def load_schema() -> dict[str, Any]:
    return json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))


def messages(schema: dict[str, Any]) -> list[Message]:
    out: list[Message] = []
    for name, d in schema["$defs"].items():
        if "x-type" not in d:
            continue
        out.append(
            Message(
                def_name=name,
                wire=d["x-type"],
                const=d["x-const"],
                direction=d["x-direction"],
                status=d.get("x-status", "stable"),
                family=d.get("x-family", "device"),
                description=d.get("description", ""),
                schema=d,
            )
        )
    wires = [m.wire for m in out]
    dupes = {w for w in wires if wires.count(w) > 1}
    if dupes:
        raise SystemExit(f"duplicate x-type in schema: {sorted(dupes)}")
    return out


def payload_defs(schema: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """Object schemas that become TypedDicts / typedefs (payloads + shared shapes)."""
    keep: dict[str, dict[str, Any]] = {}
    for name, d in schema["$defs"].items():
        if name == "Envelope" or "properties" not in d:
            continue
        keep[name] = d
    return keep


def _camel(const: str) -> str:
    head, *rest = const.lower().split("_")
    return head + "".join(p.capitalize() for p in rest)


def _agent_short(const: str) -> str:
    return const.removeprefix("AGENT_")


# ---------------------------------------------------------------- Python


def _py_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        ref = s["$ref"].rsplit("/", 1)[-1]
        return "str" if ref == "SessionId" else ref
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(_py_type({**s, "type": x}) for x in t)
    return {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
        "null": "None",
        "object": "dict[str, Any]",
        "array": f"list[{_py_type(s.get('items', {}))}]" if s.get("items") else "list[Any]",
    }.get(t, "Any")


def gen_python(schema: dict[str, Any]) -> str:
    msgs = messages(schema)
    device = [m for m in msgs if m.family == "device"]
    agent = [m for m in msgs if m.family == "agent"]
    lines = [
        f'"""{HEADER}"""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import Enum",
        "from typing import Any",
        "",
        "from typing_extensions import NotRequired, TypedDict",
        "",
        f'PROTOCOL_VERSION = "{schema["x-protocol-version"]}"',
        "",
        "",
        "class DeviceMessageType(str, Enum):",
    ]
    for direction in ("device->runtime", "runtime->device"):
        lines.append(f"    # {direction.replace('->', ' -> ')}")
        for m in device:
            if m.direction != direction:
                continue
            note = f"  # {m.status}" if m.status != "stable" else ""
            lines.append(f'    {m.const} = "{m.wire}"{note}')
    lines += ["", "", "class AgentEventType(str, Enum):"]
    for m in agent:
        lines.append(f'    {_agent_short(m.const)} = "{m.wire}"')

    defs = payload_defs(schema)
    for name, d in defs.items():
        required = set(d.get("required", []))
        lines += ["", "", f"class {name}(TypedDict):"]
        if d.get("description"):
            lines.append(f'    """{d["description"]}"""')
            lines.append("")
        props = d.get("properties", {})
        if not props:
            lines.append("    pass")
        for key, ps in props.items():
            t = _py_type(ps)
            lines.append(f"    {key}: {t}" if key in required else f"    {key}: NotRequired[{t}]")

    lines += [
        "",
        "",
        "# wire type -> $defs payload name (for schema validation)",
        "PAYLOAD_DEFS: dict[str, str] = {",
    ]
    for m in msgs:
        lines.append(f'    "{m.wire}": "{m.def_name}",')
    lines += ["}", ""]
    return "\n".join(lines)


def gen_shared_python(schema: dict[str, Any]) -> str:
    msgs = messages(schema)
    lines = [
        f'"""{HEADER}',
        "",
        "Dependency-free wire constants for standalone Python devices (clients/cli).",
        '"""',
        "",
        f'PROTOCOL_VERSION = "{schema["x-protocol-version"]}"',
        "",
        "",
        "class Msg:",
    ]
    for m in msgs:
        if m.family == "device":
            lines.append(f'    {m.const} = "{m.wire}"')
    lines += ["", "", "class AgentEvt:"]
    for m in msgs:
        if m.family == "agent":
            lines.append(f'    {_agent_short(m.const)} = "{m.wire}"')
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------- JavaScript


def _js_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        ref = s["$ref"].rsplit("/", 1)[-1]
        return "string" if ref == "SessionId" else ref
    t = s.get("type")
    if isinstance(t, list):
        return "(" + " | ".join(_js_type({**s, "type": x}) for x in t) + ")"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
        "object": "Record<string, any>",
        "array": f"Array<{_js_type(s.get('items', {}))}>" if s.get("items") else "any[]",
    }.get(t, "any")


def gen_js(schema: dict[str, Any]) -> str:
    msgs = messages(schema)
    lines = [
        f"// {HEADER}",
        "",
        f'export const PROTOCOL_VERSION = "{schema["x-protocol-version"]}";',
        "",
    ]
    lines.append("/** Device Protocol message types (envelope `type`). */")
    lines.append("export const MSG = Object.freeze({")
    for m in msgs:
        if m.family == "device":
            dep = "  /** @deprecated */\n" if m.status == "deprecated" else ""
            lines.append(f'{dep}  {m.const}: /** @type {{"{m.wire}"}} */ ("{m.wire}"),')
    lines += [
        "});",
        "",
        "/** Agent event types streamed to devices. */",
        "export const AGENT = Object.freeze({",
    ]
    for m in msgs:
        if m.family == "agent":
            lines.append(f'  {_agent_short(m.const)}: /** @type {{"{m.wire}"}} */ ("{m.wire}"),')
    lines += ["});", ""]
    for name, d in payload_defs(schema).items():
        required = set(d.get("required", []))
        lines.append("/**")
        lines.append(f" * @typedef {{object}} {name}")
        for key, ps in d.get("properties", {}).items():
            k = key if key in required else f"[{key}]"
            lines.append(f" * @property {{{_js_type(ps)}}} {k}")
        lines += [" */", ""]
    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------- Dart


def gen_dart(schema: dict[str, Any]) -> str:
    msgs = messages(schema)
    lines = [
        f"// {HEADER}",
        "library;",
        "",
        f"const protocolVersion = '{schema['x-protocol-version']}';",
        "",
        "/// Device Protocol message types (envelope `type`).",
        "abstract final class Msg {",
    ]
    for m in msgs:
        if m.family == "device":
            if m.status == "deprecated":
                lines.append("  @Deprecated('binary WebSocket frames')")
            lines.append(f"  static const {_camel(m.const)} = '{m.wire}';")
    lines += [
        "}",
        "",
        "/// Agent event types streamed to devices.",
        "abstract final class AgentEvt {",
    ]
    for m in msgs:
        if m.family == "agent":
            lines.append(f"  static const {_camel(_agent_short(m.const))} = '{m.wire}';")
    lines += ["}", ""]
    return "\n".join(lines)


TARGETS = {
    ROOT / "runtime" / "protocol" / "_generated.py": gen_python,
    ROOT / "clients" / "shared" / "protocol_gen.py": gen_shared_python,
    ROOT / "desktop" / "web" / "js" / "protocol.gen.js": gen_js,
    ROOT / "clients" / "mobile" / "lib" / "protocol" / "protocol.gen.dart": gen_dart,
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()
    schema = load_schema()
    stale: list[str] = []
    for path, gen in TARGETS.items():
        text = gen(schema)
        rel = path.relative_to(ROOT).as_posix()
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check:
            stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {rel}")
    if stale:
        print(
            "stale generated protocol files (run python scripts/gen_protocol.py):", file=sys.stderr
        )
        for rel in stale:
            print(f"  {rel}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
